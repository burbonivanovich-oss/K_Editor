// Приоритет кластеров рутины A0 (недельный бэклог тем).
//
// До этой правки generate-backlog.mjs сортировал кандидатов чисто по
// величине движения Wordstat (рост показов), без учёта того, какой
// кластер несёт. В реальном прогоне 2026-08-06 это вынесло в топ бэклога
// усн/декларация/налоги/страховые взносы — общий бухгалтерский шум,
// а профильные для Контур.Маркета темы (касса, оборудование, маркировка,
// эквайринг, ЕГАИС, Меркурий, общепит, розница, аптека) оказались
// вытеснены. Список ниже — по прямому указанию редактора: это кластеры,
// продающие продукты Контур.Маркета (см. src/data/product-mapping.json),
// плюс ekvairing/oborudovanie — без явного product в справочнике, но
// неотделимые от той же розничной/кассовой экосистемы.
//
// Множитель, не хард-фильтр: «законодательство» (nalogi, otchetnost-edo,
// kadry, buhgalteriya) остаётся в теме проекта (см. AGENTS.md — один из
// трёх заявленных столпов тематики), просто не должно выдавливать
// профильные темы из ограниченного LIMIT мест бэклога.

export const PRIORITY_CLUSTERS = new Set([
  "ts-piot",
  "kkt",
  "oborudovanie",
  "markirovka",
  "markirovka-2026",
  "ekvairing",
  "egais",
  "ofd-fn",
  "merkuriy",
  "horeca",
  "roznica",
  "apteka",
]);

// Тот же порядок величины, что «прорыв снизу весит в 1.5 раза больше
// ровного роста» в generate-backlog.mjs — второй множитель того же типа
// в том же скоринге, а не рассинхронизированное число из воздуха.
export const PRIORITY_WEIGHT = 1.5;

export function priorityMultiplier(cluster) {
  return cluster && PRIORITY_CLUSTERS.has(cluster) ? PRIORITY_WEIGHT : 1;
}
