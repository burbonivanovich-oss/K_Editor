export const COLUMN_RENAMES = new Map([
  ['документ', 'doc'],
  ['правка',   'note'],
]);

/**
 * Колонки, без которых читать вкладку нельзя.
 *
 * Не «все колонки», а тот минимум, на котором держится разбор: чем тема
 * называется (`topic`), что с ней сейчас (`status`), что решил редактор
 * (`decision`), где текст (`doc`) и по какому ключу тема сопоставляется с
 * состоянием (`slug`). Нет любой из пяти — прочитанное не значит ничего.
 *
 * Зачем понадобился явный список. До 01.09.2026 `readWork` при незнакомой
 * шапке молча переходил на чтение по номерам колонок: «раз заголовки не
 * узнаю, буду считать, что порядок как в WORK_COLS». Расчёт был на
 * вкладку, где заголовков нет вовсе. На деле сработало иначе: 23.08.2026
 * раскладку пересобрали, и рутина со старым набором колонок читала новую
 * шапку — часть заголовков совпадала («Тема», «Решение»), часть нет
 * («Ссылка на докс» вместо «Документ»). Ветка `some()` возвращала true,
 * недостающие ключи молча становились пустой строкой, и рутина
 * четырнадцать дней подряд записывала «0 снято, 0 правок» — ровно тем же
 * событием, каким она отчитывается о живой таблице без решений.
 *
 * Отсюда правило: неполная шапка — отказ читать, а не чтение вслепую.
 */
export const REQUIRED_KEYS = ['topic', 'status', 'decision', 'doc', 'slug'];

/**
 * Разбирает шапку вкладки: заголовок → индекс колонки.
 *
 * Возвращает `{ byKey, missing, unknown, ok }`. Старые названия колонок
 * читаются через COLUMN_RENAMES — вкладка, которую не прогнали через
 * sync-columns, остаётся читаемой, и это не ошибка: переименование
 * трогает заголовок, а не данные под ним.
 *
 * Пустая шапка (`ok: false`, все ключи в `missing`) — тоже отказ.
 * Позиционного запасного варианта здесь нет намеренно: он и был причиной
 * молчаливой поломки.
 */
export function resolveHeader(header = []) {
  const byTitle = new Map(WORK_COLS.map((c) => [c.title.toLowerCase(), c.key]));
  const byKey = new Map();
  const unknown = [];

  header.forEach((raw, idx) => {
    const title = String(raw || '').trim().toLowerCase();
    if (!title) return;
    const key = byTitle.get(title) || COLUMN_RENAMES.get(title);
    if (!key) { unknown.push(String(raw).trim()); return; }
    // Первое вхождение выигрывает: задвоенный заголовок — это тоже
    // расхождение раскладки, но данные под первым обычно свои.
    if (!byKey.has(key)) byKey.set(key, idx);
  });

  const missing = REQUIRED_KEYS.filter((k) => !byKey.has(k));
  return { byKey, missing, unknown, ok: missing.length === 0 };
}

