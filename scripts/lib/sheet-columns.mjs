/**
 * План приведения живой вкладки к WORK_COLS.
 *
 * Отдельная функция, а не код внутри команды drive-sync, по той же
 * причине, по которой сам список колонок живёт здесь: раскладка уже
 * трижды разъезжалась молча, и каждый раз это замечали по испорченным
 * данным, а не по упавшей проверке. Здесь она проверяема без Google.
 *
 * Шаги идут в том порядке, в котором их обязан применять вызывающий:
 * индексы каждого посчитаны по раскладке после предыдущих.
 *
 *   { kind: 'rename', title, to }   — только заголовок, данные на месте
 *   { kind: 'delete', at, title }   — колонки нет в WORK_COLS
 *   { kind: 'insert', at, title }   — новая колонка, приходит пустой
 *   { kind: 'move',   from, at, title } — перестановка, всегда справа налево
 *
 * @returns {{plan: Array, live: string[], want: string[], error: string|null}}
 *   error !== null означает «руками»: план применять нельзя.
 */
export function planColumnSync(currentTitles) {
  const want = WORK_COLS.map((c) => c.title);
  const plan = [];

  const cur = [...currentTitles].map((t) => (t || '').trim());
  while (cur.length && !cur[cur.length - 1]) cur.pop();

  /* Переименования — первым делом, до сравнения: дальше колонка
   * участвует в плане под новым именем и не выглядит ни лишней, ни
   * недостающей. Иначе «Документ» → «Ссылка на докс» читалось бы как
   * «одну удалить, другую вставить», то есть как потерю всех ссылок. */
  const live = cur.map((title) => {
    const key = COLUMN_RENAMES.get(title.toLowerCase());
    if (!key) return title;
    const renamed = WORK_COLS[workIdx(key)]?.title;
    if (!renamed || renamed === title) return title;
    plan.push({ kind: 'rename', title, to: renamed });
    return renamed;
  });

  /* Дубли — единственный случай, который автоматика разобрать не может:
   * неизвестно, в какой из двух одинаковых колонок данные. Молча выбрать
   * любую значило бы выбросить работу редактора. */
  const dupes = [...new Set(live.filter((t, i) => t && live.indexOf(t) !== i))];
  if (dupes.length) {
    return { plan: [], live, want, error: `во вкладке две колонки с одним заголовком (${dupes.join(', ')})` };
  }

  // Сначала лишние — удаление не сдвигает то, что левее.
  for (let i = live.length - 1; i >= 0; i--) {
    if (!want.includes(live[i])) { plan.push({ kind: 'delete', at: i, title: live[i] }); live.splice(i, 1); }
  }
  // Затем недостающие — слева направо, чтобы индексы совпадали с целевыми.
  want.forEach((title, i) => {
    if (!live.includes(title)) { plan.push({ kind: 'insert', at: i, title }); live.splice(i, 0, title); }
  });
  /* И наконец перестановка. Двигаем всегда справа налево (at < from): у
   * moveDimension индекс назначения считается по раскладке ДО
   * перемещения, и для движения вправо его пришлось бы поправлять на
   * единицу — лишний повод ошибиться на один столбец, а цена такой
   * ошибки здесь ровно та же, что была 11.08.2026. */
  want.forEach((title, i) => {
    if (live[i] === title) return;
    const from = live.indexOf(title);
    plan.push({ kind: 'move', from, at: i, title });
    live.splice(i, 0, live.splice(from, 1)[0]);
  });

  const error = live.join('|') === want.join('|') ? null : 'после плана раскладка всё равно не сходится';
  return { plan, live, want, error };
}
