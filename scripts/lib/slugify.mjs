/**
 * Транслитерация заголовка в slug.
 *
 * Общий модуль, а не копия в каждом скрипте, по конкретной причине.
 * Slug — это то, чем строка таблицы сшивается с темой в состоянии цикла:
 * apply-decisions ищет тему по нему, а не по номеру строки (номер сдвигается,
 * когда редактор удаляет строку). Пока slug считали в двух местах,
 * cycle-state.mjs транслитерировал заголовок, а drive-sync.mjs писал в
 * колонку «ID» то, что пришло в plan.json, — и если поля там не было,
 * колонка оставалась пустой. Все темы цикла оказывались «пропавшими»:
 * решения редактора не применялись ни к одной.
 */
const MAP = { а:'a',б:'b',в:'v',г:'g',д:'d',е:'e',ё:'e',ж:'zh',з:'z',и:'i',й:'y',к:'k',л:'l',м:'m',
  н:'n',о:'o',п:'p',р:'r',с:'s',т:'t',у:'u',ф:'f',х:'h',ц:'c',ч:'ch',ш:'sh',щ:'sch',ъ:'',ы:'y',
  ь:'',э:'e',ю:'yu',я:'ya' };

export function slugify(title) {
  return String(title).toLowerCase().split('').map((c) => MAP[c] ?? c).join('')
    .replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 60);
}
