/**
 * След старого кода в ячейках: что записано не в свою колонку.
 *
 * Откуда берётся. 23.08.2026 раскладку колонок пересобрали, но рутины
 * работали со старой: читали они по заголовкам, а **писали** по буквам,
 * посчитанным от своего порядка колонок. Каждая запись уезжала на своё
 * прежнее место, которое в новой раскладке занято другой колонкой. За
 * две недели набралось:
 *
 *   статус («снято», «на вычитке · 18 дн.») → «Формат статьи»
 *   ссылка на Google Doc                    → «Кто пишет»
 *   slug темы                               → «Ссылка Маркета»
 *
 * У «Формата» и «Кто пишет» есть выпадающие списки, поэтому редактор
 * видит россыпь красных отметок «значение не из списка» — и не может
 * пользоваться колонками по назначению.
 *
 * Правило здесь узкое намеренно: чистится только то, про что можно
 * доказать, что это машинная запись не в свою колонку. Списки колонок
 * нестрогие (`strict: false`), редактор вправе вписать свой формат или
 * свою причину, и «всё, чего нет в словаре» удалять нельзя — это стёрло
 * бы его работу. Поэтому статус в «Формате» — мусор (редактор не пишет
 * туда «на вычитке · 18 дн.»), а незнакомое слово — нет.
 *
 * Что похоже на мусор, но им не является, попадает в `suspicious`:
 * решение, вписанное редактором в «Тезисы», — это его ошибка, а не
 * машинная запись, и решать, стирать ли её, должен человек.
 */
import { RU_STATUS, WORK_COLS } from './sheet-columns.mjs';

/** Надписи статусов: их пишет только бот. */
const STATUS_WORDS = new Set(Object.values(RU_STATUS).map((v) => v.toLowerCase()));

/* «на вычитке · 18 дн.» — статус со счётчиком дней, тоже запись бота.
 *
 * Граница слова здесь пробелом, а не `\b`: `\b` в JavaScript считает
 * словом только латиницу с цифрами, поэтому после кириллического «на
 * вычитке» границы не находит и правило молча не срабатывает. */
const STATUS_WITH_DAYS = /^(на вычитке|пишется|принято|снято|в плане|кандидат|выпущено)(?:\s|$)/iu;

const isUrl = (v) => /^https?:\/\//i.test(v);

/** Слаг: латиница, цифры и дефисы, без пробелов и без схемы URL. */
const isSlug = (v) => /^[a-z0-9]+(-[a-z0-9]+){2,}$/i.test(v);

/** Решения и их прежние написания — для `suspicious`. */
const DECISION_WORDS = new Set([
  'пишем', 'не подходит', 'написать сейчас', 'принято', 'переписать статью',
  'нужно тз дизайнеру', 'убрать', 'одобрено', 'согласовано', 'отклонено', 'снять',
]);

/**
 * Ищет в прочитанных строках ячейки, записанные не в свою колонку.
 *
 * @param {Array<object>} items строки из `drive-sync pull` (item.row + ключи колонок)
 * @returns {{junk: Array, suspicious: Array}} junk — чистить, suspicious — показать человеку
 */
export function findLegacyJunk(items = []) {
  const junk = [];
  const suspicious = [];

  for (const item of items) {
    const at = (key) => String(item[key] ?? '').trim();

    const format = at('format');
    if (format && (STATUS_WORDS.has(format.toLowerCase()) || STATUS_WITH_DAYS.test(format))) {
      junk.push({ row: item.row, key: 'format', value: format, why: 'статус в колонке формата' });
    }

    const who = at('who');
    if (who && isUrl(who)) {
      junk.push({ row: item.row, key: 'who', value: who, why: 'ссылка на док в колонке исполнителя' });
    }

    const kontur = at('konturLink');
    if (kontur && !isUrl(kontur) && isSlug(kontur)) {
      junk.push({ row: item.row, key: 'konturLink', value: kontur, why: 'slug темы в колонке ссылки' });
    }

    // Ниже — не машинный след, а перепутанная колонка у человека.
    const theses = at('theses');
    if (theses && DECISION_WORDS.has(theses.toLowerCase())) {
      suspicious.push({ row: item.row, key: 'theses', value: theses, why: 'решение вписано в «Тезисы» — стирать ли, решает редакция' });
    }
  }

  return { junk, suspicious };
}

/** Заголовок колонки по ключу — для читаемого отчёта. */
export const titleOf = (key) => (WORK_COLS.find((c) => c.key === key) || {}).title || key;
