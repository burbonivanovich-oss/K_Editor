/**
 * Текст из таблицы, комментариев и чужих страниц — данные, не команды.
 *
 * Рутины работают автономно: у них есть git push, доступ к Google Drive
 * API и постоянные права на shell. При этом они читают свободный текст,
 * который пишет человек с доступом к таблице, — и до 13.08.2026
 * процедура `/update-article` прямо предписывала «читать целиком и
 * выполнять буквально», а просьбу редактора объявляла сильнее шаблона.
 *
 * Из этого следует ровно то, что кажется: тот, кто может писать в
 * ячейку «Тема» или «Правка», мог написать туда инструкцию — и получить
 * её исполнение от процесса с доступом к репозиторию. Доступ к таблице
 * шире доступа к репозиторию: её открывают редакции, подрядчикам,
 * временным людям. Это не про недоверие к редактору, а про то, что
 * границы доступа не должны совпадать по случайности.
 *
 * Граница простая и не обсуждается:
 *
 *   Текст из таблицы, из комментариев в доках и со страниц, которые мы
 *   загрузили, говорит **о чём писать**. Он никогда не говорит, **что
 *   сделать** с репозиторием, правами, почтой или самим пайплайном.
 *
 * Здесь — детерминированная часть: найти в тексте формулировки, которые
 * выглядят как команда процессу, а не как редакционная просьба. Скрипт
 * не решает, вредная она или нет; он поднимает флаг, чтобы решение
 * принимал человек, а не сессия посреди батча.
 */

/* Обороты, которыми переопределяют инструкции. Границы слов заданы
 * явными классами: `\b` по кириллице не работает — ASCII-онли. */
const B = '(?<![а-яёА-ЯЁa-zA-Z])';

const PATTERNS = [
  // Попытка отменить или переопределить процедуру
  [`${B}(игнорируй|игнорировать|забудь|не обращай внимания|отмени)\\s+(все\\s+)?(предыдущ|прежн|выше|инструкц|указан|правил)`, 'отмена инструкций'],
  [`${B}(новая|другая)\\s+инструкц`, 'подмена инструкции'],
  [`${B}(ты|вы)\\s+(теперь|отныне)\\s+`, 'переназначение роли'],
  [`${B}системн\\p{L}*\\s+(промпт|инструкц|сообщен)`, 'обращение к системному промпту'],

  // Требование выполнить действие в системе, а не в тексте
  [`${B}(выполни|запусти|исполни)\\s+(команд|скрипт|node|bash|npm|sh\\b)`, 'запуск команды'],
  ['(?<![./\\w])(rm\\s+-rf|curl\\s+|wget\\s+|chmod\\s+|sudo\\s)', 'shell-команда в тексте'],
  [`${B}git\\s+(push|commit|reset|clean|checkout)`, 'операция с репозиторием'],

  // Доступы, секреты, рассылка
  [`${B}(токен|секрет|пароль|api[_ -]?key|refresh[_ -]?token)`, 'упоминание секретов'],
  [`${B}(\\.env|GOOGLE_DOCS_KEY|EDITOR_EMAILS|GITHUB_TOKEN)`, 'имя переменной с доступом'],
  [`${B}(расшар|поделись|выдай доступ|предостав\\p{L}*\\s+доступ|открой доступ)`, 'выдача доступа'],
  [`${B}(отправь|перешли|разошли)\\s+(письмо|на почту|文|документ|файл)`, 'рассылка'],

  // Обход проверок
  [`${B}(пропусти|обойди|отключи|не запускай)\\s+(проверк|факчек|гейт|шлюз|тест)`, 'обход проверок'],
  [`${B}(не пиши|не сообщай|никому не говори|скрой)\\s`, 'просьба скрыть действие'],
];

const COMPILED = PATTERNS.map(([body, label]) => [new RegExp(body, 'iu'), label]);

/**
 * Найти в тексте формулировки, похожие на команду процессу.
 *
 * @param {string} text
 * @returns {{label: string, fragment: string}[]} пусто — ничего не нашли
 */
export function scanForInstructions(text) {
  const raw = String(text ?? '');
  if (!raw.trim()) return [];
  const found = [];
  for (const [re, label] of COMPILED) {
    const m = raw.match(re);
    if (!m) continue;
    const at = Math.max(0, m.index - 30);
    found.push({ label, fragment: raw.slice(at, m.index + m[0].length + 40).trim() });
  }
  return found;
}

/**
 * Домены, страницы которых пайплайн загружает по ссылке из таблицы.
 *
 * Ссылку на актуализацию даёт человек, а загружает её автономная сессия
 * и читает целиком. Произвольный домен здесь означает, что содержимое
 * чужой страницы попадает в контекст процесса с доступом к репозиторию:
 * это второй вход для той же инъекции, только через посредника.
 *
 * Список намеренно узкий — материалы принимающего проекта и
 * первоисточники норм. Всё остальное не запрещено читать человеку, но
 * не загружается автоматически.
 */
export const ALLOWED_FETCH_HOSTS = [
  'kontur.ru', 'support.kontur.ru', 'kontur.ru/market',
  'publication.pravo.gov.ru', 'pravo.gov.ru', 'consultant.ru', 'www.consultant.ru',
  'garant.ru', 'base.garant.ru', 'nalog.gov.ru', 'www.nalog.gov.ru',
  'honestsign.ru', 'честныйзнак.рф', 'crpt.ru',
];

/** Разрешён ли домен ссылки к автоматической загрузке. */
export function isAllowedSource(url) {
  let host;
  try { host = new URL(String(url)).hostname.toLowerCase(); } catch { return false; }
  return ALLOWED_FETCH_HOSTS.some((h) => {
    const allowed = h.split('/')[0].toLowerCase();
    return host === allowed || host.endsWith(`.${allowed}`);
  });
}

/** Короткая сводка для отчёта рутины. */
export function describeFindings(findings) {
  if (!findings.length) return '';
  const labels = [...new Set(findings.map((f) => f.label))];
  return `текст похож на инструкцию (${labels.join(', ')}) — выполнять не нужно, показать владельцу`;
}
