/**
 * Знак, модальность и субъект — то, чего не видно по числу.
 *
 * Зачем. Покрытие (`check-coverage`) отвечало на вопрос «есть ли в
 * отчёте утверждение, содержащее это число». Ответ «да» ничего не
 * говорит о том, что про число сказано. Отсюда два случая корпуса,
 * прошедшие все проверки:
 *
 * — в статье про разрешительный режим дата «1 сентября 2025» покрыта
 *   утверждением про регистрацию ККТ через Госуслуги, перенесённым из
 *   отчёта по другой статье: дата та же, утверждение — про другое;
 * — тестовая инъекция аудита: «обязана заплатить 10 000 ₽» и «не
 *   обязана платить 10 000 ₽» прошли одинаково.
 *
 * Как считается. Не по всему тексту, а по окну вокруг самого значения —
 * и в статье, и в утверждении. Первая версия сравнивала чётность
 * отрицаний по всей формулировке целиком; на корпусе это дало 30+
 * ложных срабатываний за один прогон, потому что в длинном
 * `explanation` частицы «не» набирается сколько угодно и к разбираемому
 * числу они отношения не имеют. Окно узкое намеренно: сравнивать надо
 * то, что относится к значению, а не то, что случилось рядом в абзаце.
 *
 * Границы честно. «Не менее 10 000 ₽» — не отрицание, а способ задать
 * нижнюю границу, и такие обороты исключены явным списком. Русское
 * отрицание бывает сложнее («вправе не выдавать»), субъект — сложнее
 * списка слов. Поэтому расхождение здесь означает «разобрано не
 * целиком», а не «неверно»: цена ложного срабатывания — лишний вопрос
 * человеку, цена пропуска — перевёрнутый факт в опубликованной статье.
 */

const NB = /[  ]/g;
const norm = (s) => String(s ?? '').replace(NB, ' ').replace(/\s+/g, ' ').trim().toLowerCase();

/** Сколько символов слева от значения считаем относящимися к нему. */
export const WINDOW = 45;

/* Границы придаточного. Отрицание за двоеточием, точкой с запятой или
 * тире относится к другой части фразы: в «Отчётности послабление не
 * касалось вообще: декларации сдавались по ставке 22 %» частица «не»
 * стоит при «послаблении», а не при ставке. Без этого правила окно
 * тащило чужое отрицание и объявляло расхождение на ровном месте. */
const CLAUSE = /[:;—–]|\.\s/g;

/* ── Отрицание ──────────────────────────────────────────────────────── */

/* Границы слова — через (?<!\p{L}), а не \b: \b в JS кириллицу словом не
 * считает, и правило молча не срабатывало бы вовсе. */
/* «без» и «ни» в список не входят намеренно. «Платят 25–50 % суммы
 * расчёта без кассы, но не менее 10 000 ₽» и «без обновления значение
 * 22 % может не появиться» — предлог и усилитель, а не отрицание при
 * значении. На корпусе они давали ровно два ложных срабатывания из
 * двух, и оба про предлог. Отрицание, которое нас интересует, стоит при
 * предикате: «не обязан», «нельзя», «запрещено». */
const NEGATION = /(?<!\p{L})(не|нет|нельзя|невозможно|запрещен\p{L}*|запрещён\p{L}*|отсутству\p{L}*|освобожда\p{L}*|освобожден\p{L}*|освобождён\p{L}*)(?!\p{L})/iu;

/**
 * Обороты, где «не» задаёт границу, а не отрицает.
 *
 * «Штраф не менее 10 000 ₽» — это утверждение о минимуме, и считать его
 * отрицанием значит объявлять расхождение там, где обе стороны говорят
 * одно и то же. Ровно на этих оборотах первая версия и посыпалась.
 */
/* Плюс контрастные обороты времени: «лучше заранее, а не когда токен
 * отключат 1 октября 2026» — это выбор момента, а не отрицание даты.
 * Считать их отрицанием значит краснеть на обычной редакторской
 * фразе. */
const QUANTIFIER = /(?<!\p{L})не\s+(менее|более|позднее|ранее|позже|раньше|выше|ниже|чаще|реже|превыша\p{L}*|когда|тогда)(?!\p{L})/giu;

const withoutQuantifiers = (t) => t.replace(QUANTIFIER, ' ');

/** Есть ли настоящее отрицание в куске текста. */
export function isNegative(text) {
  return NEGATION.test(withoutQuantifiers(norm(text)));
}

/* ── Модальность ────────────────────────────────────────────────────── */

/**
 * Что утверждение делает с читателем: обязывает, разрешает, запрещает
 * или просто сообщает. Обязанность и возможность — разные факты, и
 * подмена одного другим меняет решение читателя целиком.
 */
const MODALITY = [
  ['prohibition', /(?<!\p{L})(нельзя|запрещен\p{L}*|запрещён\p{L}*|не\s+вправе|не\s+допускается)(?!\p{L})/iu],
  ['obligation', /(?<!\p{L})(обязан\p{L}*|должен|должна|должно|должны|необходимо|требуется|подлежит)(?!\p{L})/iu],
  ['permission', /(?<!\p{L})(вправе|может|можете|можно|допускается|разрешен\p{L}*|разрешён\p{L}*)(?!\p{L})/iu],
];

export function modalityOf(text) {
  const t = norm(text);
  for (const [name, re] of MODALITY) if (re.test(t)) return name;
  return 'statement';
}

/* ── Субъект ────────────────────────────────────────────────────────── */

/**
 * Кого утверждение касается. Список короткий намеренно: это роли, у
 * которых в нашей тематике различаются суммы и обязанности. ИП и
 * юрлицо в ч. 2 ст. 14.5 КоАП РФ отличаются втрое по штрафу, и цитата
 * про одного не доказывает норму про другого.
 */
const SUBJECTS = [
  ['ип', /(?<!\p{L})(ип|индивидуальн\p{L}*\s+предпринимател\p{L}*)(?!\p{L})/iu],
  ['юрлицо', /(?<!\p{L})(юридическ\p{L}*\s+лиц\p{L}*|юрлиц\p{L}*|организаци\p{L}*)(?!\p{L})/iu],
  ['должностное', /(?<!\p{L})(должностн\p{L}*\s+лиц\p{L}*)(?!\p{L})/iu],
];

export function subjectsOf(text) {
  const t = norm(text);
  return SUBJECTS.filter(([, re]) => re.test(t)).map(([name]) => name);
}

/* ── Окно вокруг значения ───────────────────────────────────────────── */

/**
 * Кусок текста, относящийся к значению: несколько слов слева и сам
 * токен. Слева, потому что по-русски предикат и его отрицание стоят
 * перед числом: «не обязана платить 10 000 ₽».
 *
 * @returns {string|null} null — токена в тексте нет, сравнивать нечего.
 */
/**
 * Все окна вокруг значения, а не только первое.
 *
 * Утверждение упоминает значение по нескольку раз, и упоминания разные:
 * «Для частей первой и второй ст. 171.1 крупный размер задаёт не сама
 * ст. 171.1, а общая норма». По первому вхождению отрицания нет, по
 * второму есть — и сверка по первому объявляла расхождение там, где
 * утверждение как раз повторяет формулировку статьи.
 */
export function windowsAround(text, token, size = WINDOW) {
  const t = norm(text);
  const k = norm(token);
  if (!k) return [];
  const out = [];
  let from = 0;
  for (;;) {
    const i = t.indexOf(k, from);
    if (i === -1) break;
    from = i + k.length;
    out.push(windowAt(t, i, k, size));
  }
  return out;
}

function windowAt(t, i, k, size) {
  let left = t.slice(Math.max(0, i - size), i);
  let cut = 0;
  for (const m of left.matchAll(CLAUSE)) cut = m.index + m[0].length;
  left = left.slice(cut);
  return { left, text: left + k, hasContext: left.trim().length >= 3 };
}

export function windowAround(text, token, size = WINDOW) {
  const t = norm(text);
  const k = norm(token);
  if (!k) return null;
  const i = t.indexOf(k);
  if (i === -1) return null;
  let left = t.slice(Math.max(0, i - size), i);
  /* Обрезаем по последней границе придаточного: всё, что до неё, к
   * этому значению уже не относится. */
  let cut = 0;
  for (const m of left.matchAll(CLAUSE)) cut = m.index + m[0].length;
  left = left.slice(cut);
  return { left, text: left + k, hasContext: left.trim().length >= 3 };
}

/* ── Сравнение ──────────────────────────────────────────────────────── */

/**
 * Сходится ли утверждение отчёта с местом статьи по смыслу.
 *
 * Сравнение идёт по окнам вокруг одного и того же значения. Если
 * значения в тексте утверждения нет — сравнивать нечего, и это не
 * расхождение: связь «утверждение про это значение» устанавливает
 * покрытие, а не эта функция.
 *
 * @param {string} articleSentence — предложение статьи вокруг значения.
 * @param {string} claimText — формулировка утверждения из отчёта.
 * @param {string} token — само значение («10 000 ₽», «01.10.2026»).
 * @returns {{ok: boolean, reasons: string[]}}
 */
export function semanticsMatch(articleSentence, claimText, token) {
  /* Достаточно, чтобы сошлась одна пара окон: утверждение вправе
   * упоминать значение несколько раз, и совпадение хотя бы с одним
   * прочтением означает, что оно про это место. */
  const aws = windowsAround(articleSentence, token);
  const cws = windowsAround(claimText, token);
  if (!aws.length || !cws.length) return { ok: true, reasons: [] };

  let best = null;
  for (const a of aws) {
    for (const c of cws) {
      const r = comparePair(a, c);
      if (r.ok) return r;
      if (!best || r.reasons.length < best.reasons.length) best = r;
    }
  }
  return best;
}

function comparePair(aw, cw) {
  const reasons = [];

  /* Сравнивать можно только там, где с обеих сторон есть что сравнивать.
   * Если утверждение начинается прямо с токена («22 %» и всё), контекста
   * у него нет, и его молчание — не отрицание и не согласие. Объявлять
   * расхождение по одностороннему признаку значит краснеть на пустом
   * месте: ровно так первая версия дала 30+ ложных срабатываний. */
  if (!aw.hasContext || !cw.hasContext) return { ok: true, reasons };

  if (isNegative(aw.text) !== isNegative(cw.text)) {
    reasons.push(isNegative(aw.text)
      ? 'в статье значение под отрицанием, в отчёте — нет'
      : 'в отчёте значение под отрицанием, в статье — нет');
  }

  const am = modalityOf(aw.text);
  const cm = modalityOf(cw.text);
  /* `statement` совместим с чем угодно: отчёт вправе быть подробнее
   * статьи и наоборот. Расхождением считается только столкновение двух
   * разных ненейтральных модальностей. */
  if (am !== 'statement' && cm !== 'statement' && am !== cm) {
    reasons.push(`модальность разная: в статье «${am}», в отчёте «${cm}»`);
  }

  const as = subjectsOf(aw.text);
  const cs = subjectsOf(cw.text);
  /* Субъект сверяем, только если он назван с обеих сторон: отчёт,
   * говорящий про норму вообще, статью про ИП не опровергает. */
  if (as.length && cs.length && !as.some((x) => cs.includes(x))) {
    reasons.push(`субъект разный: в статье ${as.join('/')}, в отчёте ${cs.join('/')}`);
  }

  return { ok: reasons.length === 0, reasons };
}

/* ── Утверждение не про эту статью ──────────────────────────────────── */

/* Служебные слова и общая лексика темы: их совпадение ничего не значит,
 * потому что они есть в любой статье корпуса. */
const STOP = new Set([
  'котор', 'тольк', 'долже', 'может', 'после', 'перед', 'между', 'через',
  'налог', 'касса', 'кассо', 'чтобы', 'также', 'этого', 'этому', 'более',
  'менее', 'нужно', 'можно', 'будет', 'части', 'пункт', 'стать',
]);

/** Значимые основы слов: первые пять букв слов длиной от пяти. */
export function contentStems(text) {
  const words = norm(text).match(/\p{L}{5,}/gu) ?? [];
  return [...new Set(words.map((w) => w.slice(0, 5)).filter((w) => !STOP.has(w)))];
}

/**
 * Похоже ли, что утверждение написано не про эту статью.
 *
 * Случай G-02: в отчёте по разрешительному режиму дата «1 сентября 2025»
 * подтверждалась текстом «добавлены способы подачи заявления через
 * изготовителя ККТ и Госуслуги» — целиком перенесённым из отчёта по
 * другой статье. Ни знак, ни модальность, ни субъект тут не расходятся:
 * утверждение просто про другое. Единственный признак, который это
 * различает, — лексика: значимых слов много, и ни одного из них в
 * статье нет.
 *
 * Порог — доля, а не абсолютное число: формулировка отчёта законно
 * бывает богаче статьи, она добавляет номер нормы и её язык. Ловить надо
 * не «сказано другими словами», а «сказано про другое».
 *
 * Калибровка на живых примерах, обеих сторон.
 *
 *   0.33 — загрязнение G-02: «добавлены способы подачи заявления через
 *          изготовителя ККТ и Госуслуги» в статье про разрешительный
 *          режим (2 основы из 6);
 *   0.45 — честное утверждение языком нормы: «Крупным размером в частях
 *          третьей и четвёртой признаётся стоимость немаркированных
 *          продовольственных товаров» (5 из 11);
 *   0.46 — то же про алкоголь и никотинсодержащую продукцию (6 из 13);
 *   1.00 — утверждение, пересказывающее статью её же словами.
 *
 * Отсюда порог 0.4: он разделяет наблюдаемые случаи, но зазор между
 * 0.33 и 0.45 узкий, и это стоит знать. Признак не единственный —
 * рядом работают знак, модальность и субъект, — но в паре «то же число,
 * другая тема» он единственный, кто вообще что-то видит. Поэтому он
 * блокирует, а полоса 0.4…0.55 остаётся пометкой без блокировки.
 */
export function foreignStatement(articleText, statement, { minStems = 4, minRatio = 0.4 } = {}) {
  const stems = contentStems(statement);
  if (stems.length < minStems) return { foreign: false, hits: null, stems: stems.length, ratio: null };
  const article = norm(articleText);
  const hits = stems.filter((st) => article.includes(st)).length;
  const ratio = hits / stems.length;
  return { foreign: ratio < minRatio, hits, stems: stems.length, ratio };
}

/**
 * Предложение вокруг позиции — то, с чем сравнивать утверждение.
 *
 * Границей считается точка с пробелом, перевод строки и разделитель
 * таблицы: в таблице «соседнее предложение» — соседняя ячейка, и тащить
 * её в контекст значит смешивать два разных факта.
 */
/* Сокращения, после которых точка не заканчивает предложение. Без них
 * «ст. 171.1» рвёт фразу пополам, окно вокруг значения захватывает
 * соседнее предложение — и чужое отрицание из него объявляется
 * расхождением. Ровно так два честных утверждения из пятнадцати
 * оказались «противоречащими статье». */
const ABBR_BEFORE = /(?:^|\s)(?:ст|п|пп|ч|абз|г|гг|руб|тыс|млн|млрд|см|стр|рис|табл|№)\.$/i;

/** Точка на позиции i — конец предложения, а не сокращение или число. */
function sentenceBreakAt(src, i) {
  if (!'.!?'.includes(src[i])) return false;
  const next = src[i + 1];
  if (next !== undefined && !/\s/.test(next)) return false;
  const head = src.slice(Math.max(0, i - 12), i + 1);
  if (ABBR_BEFORE.test(head)) return false;
  /* «14.5» и «171.1»: точка между цифрами — часть номера. */
  if (/\d$/.test(src.slice(0, i)) && /^\s*\d/.test(src.slice(i + 1))) return false;
  return true;
}

export function sentenceAt(text, start, end = start) {
  const src = String(text ?? '');
  let from = 0;
  for (let i = 0; i < start; i += 1) {
    if (src[i] === '\n' || src[i] === '|') { from = i + 1; continue; }
    if (sentenceBreakAt(src, i)) from = i + 1;
  }
  let to = src.length;
  for (let i = end; i < src.length; i += 1) {
    if (src[i] === '\n' || src[i] === '|') { to = i; break; }
    if (sentenceBreakAt(src, i)) { to = i + 1; break; }
  }
  return src.slice(from, to).replace(/\s+/g, ' ').trim();
}
