// Тесты сверки «каждое значение статьи разобрано факчеком».
//
// Тестов на ложную тревогу здесь больше, чем на пропуск, и это
// намеренно. Сверка, которая ругается на номера пунктов, цифры в
// ссылках и даты, написанные словами вместо цифр, будет выключена в
// первую неделю — и тогда она не сработает и в настоящий раз. При
// калибровке на живом корпусе она успела выдать четыре ложных
// срабатывания подряд; каждое из них закреплено тестом.
//
// Запуск: node --test scripts/factcheck/check-coverage.test.mjs

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { checkCoverage, extractValues, significantKeys, normalizeDates, strip } from './check-coverage.mjs';

const article = (body) => `---\ntitle: "Т"\npubDate: "2026-08-13"\n---\n\n${body}`;
const report = (...raws) => ({ claims: raws.map((raw, i) => ({ id: `c${i}`, raw })) });
const missingTexts = (body, rep) => checkCoverage(article(body), rep).missing.map((m) => m.text);

/* ------------------------------------------------ находит пропущенное */

test('сумма, которой нет в отчёте, всплывает', () => {
  assert.deepEqual(missingTexts('Штраф составит 300 000 ₽ по норме.', report('10 000 ₽')), ['300 000 ₽']);
});

test('норма, которой нет в отчёте, всплывает', () => {
  assert.deepEqual(missingTexts('Ответственность по ст. 15.12 КоАП РФ.', report('ст. 14.5 КоАП')), ['ст. 15.12']);
});

test('дата, которой нет в отчёте, всплывает', () => {
  assert.deepEqual(missingTexts('Требование действует с 08.07.2025.', report('28.12.2025')), ['08.07.2025']);
});

test('номер тега, которого нет в отчёте, всплывает', () => {
  assert.deepEqual(missingTexts('Заполняется тег 1162.', report('54-ФЗ')), ['тег 1162']);
});

test('всё разобрано — пусто', () => {
  assert.deepEqual(missingTexts('Штраф 10 000 ₽ по ст. 14.5 КоАП.', report('10 000 ₽', 'ст. 14.5 КоАП')), []);
});

/* --------------------------------------- ложные тревоги при калибровке */

// Адрес ссылки состоит из цифр целиком, и ни одна не является
// утверждением этой статьи.
test('цифры внутри ссылки значениями не считаются', () => {
  const body = 'Подробнее в [статье](/blog/2026-08-09-kto-obyazan-do-01-10-2026/).';
  assert.deepEqual(missingTexts(body, report()), []);
});

test('служебные маркеры промоблоков и врезок не считаются', () => {
  assert.deepEqual(missingTexts('[Промоблок: 8526]\n\n[Врезка: важно]', report()), []);
});

test('нумерация списка не считается значением', () => {
  assert.deepEqual(missingTexts('1. Первый шаг\n2. Второй шаг\n3. Третий шаг', report()), []);
});

test('даты из frontmatter не считаются утверждениями', () => {
  assert.deepEqual(checkCoverage(article('Текст без чисел.'), report()).missing, []);
});

// «1 октября 2026» в статье и «01.10.2026» в отчёте — одна дата. Пока
// это не сводилось, статья вечно числилась непроверенной.
test('дата словами и дата цифрами — одно значение', () => {
  assert.deepEqual(missingTexts('Срок — 1 октября 2026 года.', report('01.10.2026')), []);
  assert.equal([...significantKeys('1 октября 2026')][0], '01102026');
  assert.match(normalizeDates('8 июля 2025'), /08\.07\.2025/);
});

// «ч. 2 ст. 14.5» и «ст. 14.5 КоАП» — про одну норму. Требовать
// совпадения всех чисел значит считать их разными.
test('номер части не делает норму непроверенной', () => {
  assert.deepEqual(missingTexts('Штраф по ч. 2 ст. 14.5 КоАП РФ.', report('ст. 14.5 КоАП')), []);
});

// «25%» из статьи и «25–50%» в отчёте — одно и то же.
test('процент внутри диапазона считается разобранным', () => {
  assert.deepEqual(missingTexts('Штраф от 25% суммы расчёта.', report('ч. 2 ст. 14.5 — 25–50% / 10 000 ₽')), []);
});

// Широкий разбор чисел склеивал соседние значения отчёта в один ключ:
// «28.12.2025 28.12.2025» превращалось в 2812202528122025, и настоящая
// дата переставала находиться.
test('соседние числа в отчёте не склеиваются в один ключ', () => {
  assert.deepEqual([...significantKeys('28.12.2025 28.12.2025')], ['28122025']);
  assert.deepEqual(missingTexts('Срок 28.12.2025.', { claims: [{ raw: '28.12.2025', expectedValue: '28.12.2025' }] }), []);
});

test('разряды тысяч читаются как одно число', () => {
  assert.ok(significantKeys('2 250 000 ₽').has('2250000'));
  assert.deepEqual(missingTexts('Порог 2 250 000 ₽.', report('2 250 000 ₽')), []);
});

/* -------------------------- короткие ссылки на нормы не совпадают наугад */

/* «Ст. 1.2» даёт ключ «12», который найдётся в любом отчёте с датой.
 * Для норм этого мало — сверяется сам текст ссылки. */
test('короткая норма не считается разобранной по случайному совпадению цифр', () => {
  assert.deepEqual(missingTexts('По ст. 1.2 закона о ККТ.', report('28.12.2025')), ['ст. 1.2']);
});

test('короткая норма, названная в отчёте прямо, считается разобранной', () => {
  const rep = { claims: [{ raw: '192-ФЗ', expectedValue: '192-ФЗ внёс в ст. 1.2 54-ФЗ правила' }] };
  assert.deepEqual(missingTexts('По ст. 1.2 закона о ККТ.', rep), []);
});

/* --------------------------------------------------- разбор и вычистка */

test('strip убирает frontmatter, ссылки и маркеры, но оставляет текст', () => {
  const out = strip(article('Штраф 10 000 ₽. [Ссылка](/blog/2026-01-01-x/) [Промоблок: 8526]'));
  assert.match(out, /10 000/);
  assert.ok(!/2026-01-01/.test(out));
  assert.ok(!/8526/.test(out));
});

test('одно значение не дублируется, даже если встречается дважды', () => {
  const vals = extractValues('Штраф 10 000 ₽ и ещё раз 10 000 ₽.');
  assert.equal(vals.length, 1);
});

test('пустой отчёт делает все значения непокрытыми, а не наоборот', () => {
  assert.deepEqual(missingTexts('Штраф 300 000 ₽.', { claims: [] }), ['300 000 ₽']);
});
