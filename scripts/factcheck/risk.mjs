/**
 * Класс риска утверждения: строгий режим доказательств или обычный.
 *
 * Строгий режим — это требование предъявить первоисточник с локатором и
 * дословной цитатой. Раньше он включался в основном для денег, УК/КоАП и
 * длительности; даты, проценты, номера ФЗ/ПП и технические версии могли
 * пройти без цитаты и источника вовсе. Между тем «требование действует с
 * 1 марта 2026», «ставка 22 %», «ПП № 1944» и «тег 1162» ошибаются с тем
 * же эффектом, что и сумма штрафа: читатель делает не то и не тогда.
 *
 * Правило: класс определяется типом и контекстом, а не объявленной
 * важностью. Severity в отчёте ставит тот же проверяющий, который
 * проверяет, и ровно эта самооценка подводила: «ФФД 1.2 нужен для тега
 * 1162» стояло `minor` при неверном номере тега. Поэтому severity может
 * поднять класс до строгого, но не может понизить.
 */

/**
 * Типы, где неверное значение меняет решение читателя: сколько заплатит,
 * по какой норме, до какого числа, что настраивать. Из закрытого списка
 * CLAIM_TYPES сюда НЕ входят только те, где значения как такового нет.
 */
export const STRICT_TYPES = [
  // деньги и доли
  'MONEY', 'MONEY_WORDS', 'MONEY_RANGE', 'PERCENT', 'QUANTITY',
  // сроки
  'DURATION', 'DATE_DMY', 'DATE_TEXT', 'DATE_YEAR', 'DATE_CONTEXT',
  // нормы
  'NPA_FZ', 'NPA_FZ_FULL', 'NPA_PP_NUMBERED', 'NPA_PRIKAZ', 'NPA_NK',
  'NPA_KOAP', 'NPA_UK', 'NPA_PUNKT',
  'LEGAL_CLAIM', 'LEGAL_RULE',
  // техника: номер тега или версия формата — такое же значение
  'TECH', 'TAG',
];

/** Типы без проверяемого значения: ссылка, тема, свободное утверждение. */
export const SOFT_TYPES = ['LINK', 'TOPIC', 'CLAIM', 'FACT'];

/* Контекст поверх типа. Ответственность, вступление требования в силу и
 * прямое указание к действию — строгий режим независимо от того, каким
 * типом утверждение записали. */
const LIABILITY = /(штраф|порог|крупн\p{L}*\s+размер|ответственност|конфискац|наказ|санкц|блокир|аннулир|приостанов)/iu;
const IN_FORCE = /(вступа\p{L}*\s+в\s+силу|с\s+\d{1,2}\s+\p{L}+\s+\d{4}|с\s+\d{1,2}\.\d{2}\.\d{4}|не\s+позднее|до\s+\d{1,2}[.\s]|переходн\p{L}*\s+период|обязан\p{L}*\s+с\s+)/iu;
const OPERATIONAL = /(нужно|необходимо|обязан|следует|требуется|настро|подключ|заявлен|подать|зарегистрир)\p{L}*/iu;
const TECH_ID = /(тег|реквизит|ффд|код\s+(ошибки|товара|маркировки)|версия\s+формата)\D{0,20}\d{3,}/iu;

const textOf = (c) => `${c?.raw ?? ''} ${c?.expectedValue ?? ''} ${c?.statement ?? ''} ${c?.explanation ?? ''}`;

/**
 * @returns {{strict: boolean, reason: string}} — причина нужна в
 *   сообщении гейта: «строгий режим, потому что это срок вступления»
 *   объясняет требование, а «строгий режим» — нет.
 */
export function riskOf(claim) {
  const t = textOf(claim);
  if (STRICT_TYPES.includes(claim?.type)) return { strict: true, reason: `тип ${claim.type}` };
  if (claim?.severity === 'critical') return { strict: true, reason: 'severity critical' };
  if (LIABILITY.test(t)) return { strict: true, reason: 'ответственность или санкция' };
  if (IN_FORCE.test(t)) return { strict: true, reason: 'срок вступления требования' };
  if (TECH_ID.test(t)) return { strict: true, reason: 'технический идентификатор' };
  if (OPERATIONAL.test(t)) return { strict: true, reason: 'указание к действию' };
  return { strict: false, reason: SOFT_TYPES.includes(claim?.type) ? `тип ${claim.type}` : 'значения нет' };
}

export const isStrict = (claim) => riskOf(claim).strict;
