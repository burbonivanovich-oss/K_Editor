/**
 * Хеши артефактов факчека: точная версия текста и его смысл.
 *
 * Один хеш решить задачу не может. `sha256` всего файла ловит любую
 * правку — включая ту, которую делает сам release, снимая `draft`.
 * Поэтому маркер после выпуска приходилось перевыписывать, и это
 * открывало дыру: перевыписать маркер можно было и после смысловой
 * правки. Отчёт своего хеша статьи не хранил вовсе, так что сверять
 * было не с чем — правка «не обязан» → «обязан» получала свежий маркер
 * со старыми доказательствами, если набор чисел не менялся.
 *
 * Отсюда два хеша:
 *
 *   articleHash     — sha256 файла как есть. Отвечает на вопрос «та ли
 *                     это в точности версия текста».
 *   articleNormHash — sha256 нормализованного текста. Отвечает на
 *                     вопрос «то же ли это по смыслу».
 *
 * Разошёлся только первый — правка косметическая (safe-diff), маркер
 * можно перевыписать без нового факчека. Разошёлся второй — текст
 * изменился по существу, и старые доказательства к нему не относятся.
 *
 * Нормализация намеренно уже, чем «пробелы и пунктуация» из внешнего
 * аудита: она гасит ровно те различия, которые появляются механически —
 * снятый `draft`, пересчитанные `updatedDate`/`reviewDate`, обратные
 * слеши и кривые тире из экспорта Google Docs, хвостовые пробелы,
 * неразрывные пробелы. Добавленная или убранная запятая под safe-diff
 * НЕ попадает: внутри числа она меняет значение («10,5%» и «105%»), а
 * разбирать, где она внутри числа, а где нет, — источник тихих ошибок.
 * Строже, чем разрешено, безопаснее: цена — лишний прогон факчека.
 */
import { createHash } from 'node:crypto';
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const sha = (s) => createHash('sha256').update(s).digest('hex');

/** Поля frontmatter, которые меняет сам конвейер, а не автор. */
export const VOLATILE_FRONTMATTER = ['draft', 'updatedDate', 'reviewDate'];

/** Точная версия файла. */
export const articleHash = (raw) => sha(String(raw));

/**
 * Текст без механических различий.
 *
 * Порядок важен: сначала снимаем волатильный frontmatter, потом
 * экранирование, потом варианты символов, и только в конце схлопываем
 * пробелы — иначе замена «— » на «-» оставляла бы двойные пробелы.
 */
export function normalizeArticle(raw) {
  let t = String(raw);

  /* Хвостовые пробелы после `---` бывают в экспорте из Docs, и без
   * терпимости к ним frontmatter просто не находился: волатильные поля
   * оставались в тексте, и снятие draft переставало быть safe-diff. */
  const fm = t.match(/^---[ \t]*\n([\s\S]*?)\n---[ \t]*\n?/);
  if (fm) {
    const kept = fm[1]
      .split('\n')
      .filter((line) => !VOLATILE_FRONTMATTER.some((k) => new RegExp(`^${k}\\s*:`).test(line)))
      .join('\n');
    t = `${kept}\n${t.slice(fm[0].length)}`;
  }

  t = t.replace(/\\([[\]().\-*_#])/g, '$1');          // экранирование из Docs
  t = t.replace(/[   ]/g, ' ');        // неразрывные пробелы
  t = t.replace(/[‐-―−]/g, '-');       // тире всех видов
  t = t.replace(/[«»“”„‟"']/g, '"');                  // кавычки всех видов
  t = t.replace(/[…]/g, '...');                  // многоточие одним символом
  t = t.replace(/\s+/g, ' ').trim();                  // пробелы и переносы

  return t;
}

/** Смысловой отпечаток текста. */
export const articleNormHash = (raw) => sha(normalizeArticle(raw));

/** Разошлась ли только форма: файл другой, смысл тот же. */
export const isSafeDiff = (raw, report) =>
  Boolean(report?.articleNormHash) && report.articleNormHash === articleNormHash(raw);

/** Хеш файла отчёта — ловит правку отчёта после выписки маркера. */
export const reportHash = (fileText) => sha(String(fileText));

/**
 * Хеш утверждений, независимый от форматирования файла.
 *
 * Ключи сортируются: переставленные поля — не изменение отчёта, а
 * переформатирование, и различать их незачем.
 */
export function claimsHash(claims) {
  const canon = (v) => {
    if (Array.isArray(v)) return v.map(canon);
    if (v && typeof v === 'object') {
      return Object.fromEntries(Object.keys(v).sort().map((k) => [k, canon(v[k])]));
    }
    return v;
  };
  return sha(JSON.stringify(canon(claims ?? [])));
}

/**
 * Отпечаток редполитики — вместо даты файла.
 *
 * `policyVersion` был датой последнего изменения `editorial-policy.md`
 * по git-истории. Дату можно поднять, не перепроверяя ничего: достаточно
 * тронуть файл или переписать поле в отчёте, и старый разбор начинал
 * выглядеть сделанным по свежим правилам. Отпечаток так не поднимешь —
 * он равен содержимому политики, и если содержимое другое, значит
 * правила другие, а разбор к ним не относится.
 */
export function policyHash(root) {
  const p = join(root, 'docs/editorial-policy.md');
  return existsSync(p) ? sha(readFileSync(p, 'utf8')) : null;
}
