/**
 * H-04. Знак, модальность и субъект.
 *
 * Здесь два требования, и они тянут в разные стороны. Ловить смысловую
 * подмену — «обязана» → «не обязана» при том же числе. И не краснеть на
 * обычном тексте: детектор, который срабатывает на каждом втором абзаце,
 * выключают через неделю, и тогда он не ловит вообще ничего. Поэтому
 * тесты идут парами: мутация обязана ловиться, живая фраза рядом — нет.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import {
  semanticsMatch, isNegative, modalityOf, subjectsOf, windowAround, sentenceAt,
} from './semantics.mjs';

const m = (a, c, t) => semanticsMatch(a, c, t);

test('отрицание при предикате ловится', () => {
  const same = 'организация обязана заплатить 10 000 ₽ по ч. 2 ст. 14.5 КоАП РФ';
  assert.ok(m('Организация обязана заплатить 10 000 ₽ штрафа.', same, '10 000 ₽').ok);

  const flipped = m('Организация не обязана платить 10 000 ₽ штрафа.', same, '10 000 ₽');
  assert.ok(!flipped.ok, 'подмена «обязана» → «не обязана» прошла незамеченной');
  assert.match(flipped.reasons[0], /под отрицанием/);
});

test('«не менее» — граница, а не отрицание', () => {
  assert.ok(!isNegative('штраф не менее 10 000 ₽'));
  assert.ok(!isNegative('не позднее рабочего дня, следующего за днём расчёта'));
  assert.ok(isNegative('не обязан применять'));
  assert.ok(m('Для ИП штраф не менее 10 000 ₽.', 'для ИП штраф не менее 10 000 ₽', '10 000 ₽').ok);
});

test('«без» и «ни» отрицанием не считаются — это предлог и усилитель', () => {
  /* Оба давали ложные срабатывания на живом корпусе: «платят 25–50 %
   * суммы расчёта без кассы, но не менее 10 000 ₽». */
  assert.ok(!isNegative('суммы расчёта без кассы'));
  assert.ok(!isNegative('ни один поставщик'));
});

test('подмена модальности ловится', () => {
  const r = m('Продавец обязан подключить модуль до 01.10.2026.',
    'продавец вправе подключить модуль до 01.10.2026', '01.10.2026');
  assert.ok(!r.ok);
  assert.match(r.reasons[0], /модальность/);
  assert.equal(modalityOf('обязан подключить'), 'obligation');
  assert.equal(modalityOf('вправе не выдавать'), 'permission');
  assert.equal(modalityOf('нельзя продавать'), 'prohibition');
  assert.equal(modalityOf('порог составляет 3 500 000 ₽'), 'statement');
});

test('нейтральная формулировка совместима с любой — отчёт вправе быть подробнее', () => {
  /* Статья сообщает, отчёт обязывает: это не столкновение модальностей,
   * а разная подробность. Расхождение — только между двумя разными
   * ненейтральными: обязанность против разрешения. */
  assert.ok(m('Штраф составляет 30 000 ₽.', 'юрлицо обязано уплатить 30 000 ₽', '30 000 ₽').ok);
  assert.ok(m('Порог — 30 000 ₽.', 'порог по норме 30 000 ₽', '30 000 ₽').ok);
});

test('подмена субъекта ловится, а умолчание — нет', () => {
  const bad = m('Юридическое лицо платит 30 000 ₽.', 'индивидуальный предприниматель платит 30 000 ₽', '30 000 ₽');
  assert.ok(!bad.ok);
  assert.match(bad.reasons[0], /субъект разный/);

  /* Отчёт про норму вообще статью про ИП не опровергает. */
  assert.ok(m('Индивидуальный предприниматель платит 30 000 ₽.', 'норма устанавливает 30 000 ₽', '30 000 ₽').ok);
  assert.deepEqual(subjectsOf('для ИП и должностных лиц'), ['ип', 'должностное']);
});

test('окно обрезается по границе придаточного', () => {
  /* «Отчётности послабление не касалось вообще: декларации сдавались по
   * ставке 22 %» — отрицание относится к послаблению, а не к ставке.
   * Без обреза по двоеточию это ложное расхождение. */
  const w = windowAround('послабление не касалось вообще: декларации сдавались по ставке 22 %', '22 %');
  assert.ok(!/не\s+касалось/.test(w.text), `в окно попало чужое отрицание: ${w.text}`);
  assert.ok(m('Отчётности послабление не касалось вообще: декларации сдавались по ставке 22 %.',
    'с 01.01.2026 основная ставка НДС — 22 %', '22 %').ok);
});

test('утверждение без контекста вокруг значения не считается противоречащим', () => {
  /* Токен в начале формулировки: контекста нет, и молчание — не ответ. */
  assert.ok(m('Организация не обязана платить 10 000 ₽.', '10 000 ₽', '10 000 ₽').ok);
  assert.equal(windowAround('10 000 ₽ и далее', '10 000 ₽').hasContext, false);
});

test('значения нет в утверждении — сравнивать нечего', () => {
  assert.ok(m('Штраф 10 000 ₽.', 'совсем про другое', '10 000 ₽').ok);
});

test('sentenceAt не тащит соседнюю ячейку таблицы', () => {
  const table = '| Приход | 10 000 ₽ | не применяется |';
  const i = table.indexOf('10 000 ₽');
  const s = sentenceAt(table, i, i + 8);
  assert.ok(!/не применяется/.test(s), `в предложение попала соседняя ячейка: ${s}`);
});

test('sentenceAt берёт предложение, а не абзац', () => {
  const p = 'Первое предложение про 30 000 ₽. Второе про другое.';
  const i = p.indexOf('30 000 ₽');
  assert.equal(sentenceAt(p, i, i + 8), 'Первое предложение про 30 000 ₽.');
});
