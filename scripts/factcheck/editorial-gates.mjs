/**
 * L-03…L-05. Редакционные проверки, которые не про факты.
 *
 * Три разных вопроса, но повод у них общий: материал бывает фактически
 * безупречным и при этом бесполезным или опасным.
 *
 * L-03, исполнимость финального призыва. Из 45 финальных пунктов корпуса
 * ни один не содержал одновременно ответственного, срок или триггер и
 * проверяемый результат. «Проверьте версию ФФД» — это не задача: не
 * сказано, кто проверяет, когда и как понять, что проверено. Такой пункт
 * читатель прочитывает и не делает, а материал числится завершённым.
 *
 * L-04, FAQ вместо FAQ. По аудиту 46 из 50 вопросов пересказывали
 * основной текст. Раздел «частые вопросы», отвечающий на то, что уже
 * сказано выше, — это не помощь читателю, а способ добрать объём и
 * ключи. Проверяется пересечение ответа с телом статьи.
 *
 * L-05, категоричность без области применимости. В корпусе 115 вхождений
 * «только», «все», «никогда», «обязан», «нельзя». Само по себе это не
 * дефект: «обязан» в правовом материале уместно. Дефект — категоричность
 * без условий, и ровно она дала две ошибки прохода: «услуги блокируют
 * накопитель досрочно» и «касса обязана остановить продажу».
 *
 * Все три возвращают замечания, а не блокируют. Причина простая:
 * решение здесь редакционное. Автоматика умеет показать место и
 * сформулировать вопрос; ответить «здесь категоричность уместна» может
 * только человек, и отнимать у него это право значит получить обход.
 */

import { splitSentences } from './classify.mjs';

const norm = (s) => String(s ?? '').replace(/[  ]/g, ' ').replace(/\s+/g, ' ').trim();
const lower = (s) => norm(s).toLowerCase();

/** Тело без frontmatter. */
const body = (src) => {
  const m = String(src).match(/^---[ \t]*\n[\s\S]*?\n---[ \t]*\n?/);
  return m ? src.slice(m[0].length) : src;
};

/* ── L-03. Исполнимость финального призыва ──────────────────────────── */

/* Ответственный: роль названа явно. «Проверьте» без роли — это «кто-то». */
const WHO = /(?<!\p{L})(кассир\p{L}*|администратор\p{L}*|бухгалтер\p{L}*|руководител\p{L}*|владелец|ИП|юрлиц\p{L}*|поставщик\p{L}*|подрядчик\p{L}*|вы|ваш\p{L}*)(?!\p{L})/iu;

/* Триггер или срок: когда это делать. */
/* Триггер — это и календарь («до 1 октября 2026»), и событие («сразу
 * после подключения», «до первой смены»), и период («на этой
 * неделе», «раз в квартал»). Первая версия знала только календарь
 * и объявляла неисполнимыми пункты, у которых триггер как раз есть. */
const WHEN = /(?<!\p{L})(до\s+\d|до\s+\p{L}+\s+\d{4}|с\s+\d{1,2}[.\s]|сегодня|сейчас|до\s+начала|до\s+перв\p{L}*|до\s+того|перед\s+\p{L}+|после\s+\p{L}+|при\s+\p{L}+|если\s+\p{L}+|раз\s+в\s+\p{L}+|на\s+(?:этой|следующей)\s+\p{L}+|ежемесячн\p{L}*|ежекварт\p{L}*|ежегодн\p{L}*|ежедневн\p{L}*|заранее|сразу)(?!\p{L})/iu;

/* Проверяемый результат: как понять, что сделано. */
const RESULT = /(?<!\p{L})(убедит\p{L}*|проверьте,\s+что|появ\p{L}*|отобраз\p{L}*|должн\p{L}*\s+быть|станет|получите|увидите|совпад\p{L}*|результат\p{L}*)(?!\p{L})/iu;

/**
 * Финальные пункты «что делать дальше».
 *
 * Ищем последний раздел с таким заголовком и берём его пункты списка:
 * именно они читаются как задачи и именно их читатель уносит с собой.
 */
export function finalActions(raw) {
  const text = body(String(raw ?? ''));
  const lines = text.split('\n');
  let start = -1;
  lines.forEach((l, i) => {
    if (/^#{2,4}\s+(что делать дальше|что сделать|дальнейшие шаги|чек-лист)/i.test(l.trim())) start = i;
  });
  if (start === -1) return [];
  const out = [];
  for (let i = start + 1; i < lines.length; i += 1) {
    const t = lines[i].trim();
    if (/^#{2,4}\s+/.test(t)) break;
    const m = t.match(/^(?:[-*]|\d+[.)])\s+(.*)$/);
    if (m && norm(m[1])) out.push({ line: i + 1, text: norm(m[1]) });
  }
  return out;
}

/**
 * L-03. Чего не хватает пункту, чтобы стать задачей.
 * @returns {Array<{line, text, missing: string[]}>}
 */
export function checkActionability(raw) {
  return finalActions(raw)
    .map((a) => {
      const missing = [];
      if (!WHO.test(a.text)) missing.push('ответственный');
      if (!WHEN.test(a.text)) missing.push('срок или триггер');
      if (!RESULT.test(a.text)) missing.push('проверяемый результат');
      return { ...a, missing };
    })
    .filter((a) => a.missing.length);
}

/* ── L-04. FAQ, который пересказывает статью ────────────────────────── */

/** Значимые основы: первые пять букв слов длиной от пяти. */
const stems = (t) => new Set((lower(t).match(/\p{L}{5,}/gu) ?? []).map((w) => w.slice(0, 5)));

/**
 * Пары «вопрос — ответ» из раздела частых вопросов.
 *
 * Два написания: `### Вопрос?` с ответом ниже и `**Вопрос?**` строкой.
 */
export function faqPairs(raw) {
  const text = body(String(raw ?? ''));
  const lines = text.split('\n');
  const pairs = [];
  let current = null;
  const flush = () => { if (current && current.answer.trim()) pairs.push({ ...current, answer: norm(current.answer) }); current = null; };

  for (const [i, rawLine] of lines.entries()) {
    const t = rawLine.trim();
    const asHeading = t.match(/^#{3,4}\s+(.+)$/);
    const asBold = t.match(/^\*\*(.+\?)\*\*$/);
    if (asHeading || asBold) {
      flush();
      const q = (asHeading ? asHeading[1] : asBold[1]).trim();
      current = { line: i + 1, question: q, answer: '' };
      continue;
    }
    if (/^#{2}\s+/.test(t)) { flush(); continue; }
    if (current) current.answer += ` ${t}`;
  }
  flush();
  return pairs;
}

/**
 * L-04. Ответы, которые почти целиком есть в теле статьи.
 *
 * Порог 0.8 намеренно высокий: FAQ законно повторяет термины и нормы из
 * статьи, и требовать полной новизны значило бы запрещать связность.
 * Ловим случай, когда ответ не добавляет ничего.
 */
export function checkFaqNovelty(raw, { threshold = 0.8 } = {}) {
  const text = body(String(raw ?? ''));
  const pairs = faqPairs(raw);
  if (!pairs.length) return [];

  /* Тело статьи без самого FAQ: сравнивать ответ с ним же бессмысленно. */
  const cut = text.search(/^#{2}\s+(частые вопросы|вопросы и ответы|faq)/im);
  const main = stems(cut === -1 ? text : text.slice(0, cut));

  return pairs
    .map((p) => {
      const st = [...stems(p.answer)];
      if (st.length < 5) return null;
      const overlap = st.filter((x) => main.has(x)).length / st.length;
      return overlap >= threshold
        ? { ...p, overlap: Number(overlap.toFixed(2)), stems: st.length }
        : null;
    })
    .filter(Boolean);
}

/* ── L-05. Категоричность без области применимости ──────────────────── */

/* «обязан», а не «обязан\p{L}*»: «обязанность применять ККТ» —
 * существительное, оно называет предмет, а не предъявляет требование
 * читателю. Ловим краткие формы предиката, ими и делаются
 * категоричные утверждения. */
const CATEGORICAL = /(?<!\p{L})(только|все|всегда|никогда|невозможно|нельзя|обязан|обязана|обязано|обязаны|любой|любая|каждый|исключительно)(?!\p{L})/giu;

/* Что делает категоричность уместной: названы условия, субъект или норма. */
const QUALIFIER = /(?<!\p{L})(если|при\s+\p{L}+|кроме|за\s+исключением|для\s+\p{L}+|когда|с\s+\d{1,2}[.\s]|ст\.|стать|пункт|п\.\s*\d|при\s+услови)(?!\p{L})/iu;

/**
 * L-05. Категоричные утверждения без условий рядом.
 *
 * Область ищем в пределах предложения: условие через два абзаца читатель
 * к этой фразе не отнесёт, и проверка не должна.
 */
export function checkCategorical(raw) {
  /* Заголовок связанной статьи в тексте ссылки — не утверждение этой
   * статьи: «[кто обязан, сроки и штрафы]» это название соседнего
   * материала. Гасим текст ссылок пробелами той же длины, чтобы номера
   * строк остались настоящими. */
  const text = body(String(raw ?? ''))
    .replace(/\[([^\]]*)\]\(([^)]*)\)/g, (m) => m.replace(/[^\n]/g, ' '));
  const out = [];

  /* Границы предложения берём у классификации, а не считаем заново.
   * Своя версия резала фразу на «ст.» и «п. 5», и условие, стоящее за
   * сокращением, в предложение не попадало: замечание появлялось ровно
   * там, где область как раз названа. Одно определение «предложения» на
   * весь репозиторий — и такие расхождения перестают быть возможными. */
  text.split('\n').forEach((rawLine, i) => {
    for (const sentence of splitSentences(rawLine)) {
      if (QUALIFIER.test(sentence)) continue;
      for (const m of sentence.matchAll(CATEGORICAL)) {
        out.push({ line: i + 1, word: m[0], sentence: sentence.slice(0, 120) });
      }
    }
  });
  return out;
}

/** Всё сразу — для гейта и для health. */
export function editorialFindings(raw) {
  return {
    actionability: checkActionability(raw),
    faq: checkFaqNovelty(raw),
    categorical: checkCategorical(raw),
  };
}
