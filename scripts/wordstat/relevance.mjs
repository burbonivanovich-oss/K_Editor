  "эдо", "кэдо", "упд", "эпд", "этрн", "мчд", "документооборот",
  "трудов", "сотрудник", "работник", "кадров", "зарплат", "мрот", "штраф",
  "закон", "требован", "срок", "лиценз", "проверк", "учёт", "учет",
