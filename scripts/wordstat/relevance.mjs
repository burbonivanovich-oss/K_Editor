// Отбор фраз, пригодных как тема статьи.
//
// Общий фильтр для двух потребителей: enrich-candidates.mjs (что отправить
// в /dynamics) и topics/generate-backlog.mjs (запасной путь по сырой
// выгрузке). Держим в одном месте — иначе один потребитель чинят, а второй
// продолжает пропускать «ретроградный меркурий».

// Навигационный интент: человек ищет вход в сервис, а не объяснение темы.
// Такие фразы собирают миллионы показов и как темы статей бесполезны —
// без этого фильтра весь верх бэклога занимает «сбис личный кабинет».
const NOISE = [
  // навигация: человек ищет вход в сервис, а не объяснение темы
  "личный", "кабинет", "лк ", "вход", "войти", "скачать", "установить",
  "официальный сайт", "https", "www", "телефон", "адрес", "горячая линия",
  "техподдержка", "отзыв", "промокод", "скидк", "купить", "цена",
  // омонимы широких сидов: «меркурий» ловит астрологию, «отпуск» — кино
  "ретроградн", "гороскоп", "фильм", "сериал", "смотреть", "онлайн бесплатно",
  "песня", "игра", "фото", "картинк",
  "интернет магазин", "ru интернет", "wb ru", " ru ",
  // омонимы «меркурия»: астрология и подвесные моторы
  "лодочн", "мотор", "планет", "в июле", "в августе", "в сентябре",
];

// Тематические маркеры МСБ. Фраза без единого маркера почти наверняка
// пришла из омонима широкого сида: выгрузка по слову «меркурий» приносит
// и ветеринарную систему, и планету. Отсеиваем на входе, а не глазами.
const DOMAIN = [
  "ип", "ооо", "бизнес", "предприниматель", "самозанят", "юрлиц",
  "налог", "ндс", "усн", "патент", "енс", "енп", "взнос", "ндфл", "отчётност",
  "отчетност", "декларац", "фнс", "сфр",
  "касс", "ккт", "офд", "фискальн", "чек", "эквайринг", "ффд",
  "маркировк", "честный знак", "честном знаке", "data matrix", "код маркировки",
  // «меркурий» из маркеров убран: система ВетИС называется так же, как
  // планета и как лодочные моторы, и слово тянуло в бэклог «меркурий в
  // июле» (+7565%, ретроградный) и «лодочный мотор меркурий». Ветеринарные
  // темы ловятся по «ветеринарн», «всд» и «ветис» — без омонимов.
  "егаис", "алкогол", "ветеринарн", "ветис", "всд",
  "эдо", "кэдо", "упд", "эпд", "этрн", "мчд", "документооборот",
  "трудов", "сотрудник", "работник", "кадров", "зарплат", "мрот", "штраф",
  "закон", "требован", "срок", "лиценз", "проверк", "учёт", "учет",
  // Голых названий площадок здесь намеренно нет: они пропускали навигацию
  // вида «wildberries ru интернет магазин». Наши темы про маркетплейсы всё
  // равно содержат «маркетплейс», «налог», «поставщик» или «ндс».
  "маркетплейс", "поставщик", "селлер",
  "тс пиот", "разрешительн",
];

function isInformational(phrase, minWords = 3) {
  const p = phrase.toLowerCase();
  if (p.trim().split(/\s+/).length < minWords) return false;
  if (NOISE.some((n) => p.includes(n))) return false;
  if (isGlued(phrase)) return false;
  // Маркер ищем по границе слова, иначе «ип» находится внутри «типа»,
  // а «срок» внутри «сроках» — второе нужно, первое нет.
  return DOMAIN.some((d) =>
    d.includes(" ") ? p.includes(d) : new RegExp(`(^|[^а-яёa-z])${d}`, "i").test(p),
  );
}


export { NOISE, DOMAIN, isInformational };

/* ─────────────────────────────────────────────── склейки и дубли ──── */

// Грубая основа слова: рубим окончание. Полноценный стеммер для русского
// тут не нужен — задача не морфология, а схлопывание вариантов одного
// запроса, где различие обычно в хвосте: «маркировки» / «маркировка».
// Обрезка до префикса фиксированной длины. Русские окончания бывают от
// одного до трёх символов, поэтому «отрезать N с конца» не выравнивает
// «знак» и «знака»; префикс выравнивает.
//
// Длина префикса разная у двух задач, и это намеренно. Схлопывание дублей
// ошибается дорого: слить «налог» и «наличные» значит потерять тему, —
// поэтому четыре символа. Детекция склейки ошибается дёшево: лишний флаг
// на одной фразе из тысяч, — поэтому три, иначе «чек» и «чека» не сойдутся.
function stem(word, len = 4) {
  return word.length <= len - 1 ? word : word.slice(0, len);
}

// Служебные и вопросительные слова. Выкидываем их перед сравнением:
// «может ли самозанятый», «могут ли самозанятые» и «можно ли самозанятый»
// — один интент и одна тема, а различаются только модальным глаголом.
const STOP = new Set([
  "в", "на", "для", "и", "с", "к", "у", "о", "из", "за", "по", "от", "до",
  "а", "но", "же", "ли", "это", "есть", "не",
  "что", "как", "где", "когда", "почему", "зачем", "какой", "какие", "такое",
  "можно", "может", "могут", "нужно", "нужен", "нужна", "нужны", "надо",
]);

/**
 * Ключ схлопывания. Фразы с одинаковым ключом — переформулировки одного
 * запроса; в бэклог из них должна попасть одна, иначе три места из
 * пятнадцати займут «может/могут/можно ли самозанятый».
 */
/** Значимые основы фразы — сырьё и для ключа схлопывания, и для сравнения. */
function stemTokens(phrase) {
  const words = phrase
    .toLowerCase()
    .replace(/[^а-яёa-z0-9\s]/gi, " ")
    .split(/\s+/)
    .filter(Boolean);
  const meaningful = words.filter((w) => !STOP.has(w)).map((w) => stem(w));
  return meaningful.length ? meaningful : words;
}

function dedupeKey(phrase) {
  return [...stemTokens(phrase)].sort().join(" ");
}

/**
 * Склейка от самого Wordstat: «чек коррекции чека коррекции». Как тема
 * статьи это мусор, но по формальным признакам фраза проходит — три слова,
 * тематическая. Признак — повторяющиеся основы: у склейки их две и больше.
 */
function isGlued(phrase) {
  const words = phrase
    .toLowerCase()
    .split(/\s+/)
    .filter(Boolean)
    .map((w) => stem(w, 3));
  if (words.length < 4) return false;
  return words.length - new Set(words).size >= 2;
}

export { dedupeKey, stemTokens, isGlued, stem };
