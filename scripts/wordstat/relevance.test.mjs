// Тесты фильтра «годится ли фраза как тема статьи».
//
// Через него проходят все 3927 кандидатов недельной выгрузки. Каждая
// строка списка NOISE и DOMAIN появилась после конкретного мусора,
// доехавшего до редактора: «сбис личный кабинет» в верху бэклога,
// «меркурий в июле» с ретроградной планетой, «лодочный мотор меркурий».
// Тесты держат оба края: шум не проходит, наши темы не отсекаются.
//
// Запуск: node --test scripts/wordstat/relevance.test.mjs

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { isInformational, dedupeKey, stemTokens, isGlued } from './relevance.mjs';

/* ---------------------------------------------------------- что проходит */

test('нормальные темы проходят', () => {
  for (const p of [
    'маркировка обуви в рознице',
    'как подключить тс пиот к кассе',
    'штраф за работу без ккт',
    'ндс 22 процента с 2026 года',
    'ветеринарные сопроводительные документы на партию',
  ]) {
    assert.ok(isInformational(p), `должно проходить: ${p}`);
  }
});

/* -------------------------------------------------------- что не проходит */

test('навигация отсекается — человек ищет вход, а не объяснение', () => {
  for (const p of [
    'сбис личный кабинет вход',
    'честный знак официальный сайт',
    'скачать программу для маркировки',
    'горячая линия честный знак телефон',
  ]) {
    assert.ok(!isInformational(p), `не должно проходить: ${p}`);
  }
});

test('омонимы широких сидов отсекаются', () => {
  for (const p of [
    'ретроградный меркурий в июле',
    'лодочный мотор меркурий цена',
    'касса театра большого',
  ]) {
    assert.ok(!isInformational(p), `омоним не должен проходить: ${p}`);
  }
});

test('слишком короткая фраза не тема', () => {
  assert.ok(!isInformational('маркировка обуви', 3));
  assert.ok(isInformational('маркировка обуви в рознице', 3));
});

test('фраза без нашего домена не проходит, даже если длинная', () => {
  assert.ok(!isInformational('как выбрать велосипед для города взрослому'));
});

// Маркер ищется по границе слова: «ип» не должно находиться внутри «типа»,
// а «срок» внутри «сроках» — должно.
test('маркер домена ищется по границе слова', () => {
  assert.ok(!isInformational('выбор типа освещения в квартире'), '«ип» внутри «типа» — не маркер');
  assert.ok(isInformational('какие сроки маркировки действуют сейчас'), '«срок» внутри «сроки» — маркер');
});

/* ------------------------------------------------------------- дедуп-ключ */

test('перестановка слов даёт один ключ схлопывания', () => {
  assert.equal(
    dedupeKey('маркировка товара честный знак'),
    dedupeKey('честный знак маркировка товара'),
  );
});

test('разные темы дают разные ключи', () => {
  assert.notEqual(dedupeKey('маркировка обуви'), dedupeKey('маркировка молока'));
});

// Регрессия: covered-фильтр заполнялся normalize, а проверялся dedupeKey —
// строки не совпадали никогда, и 13 из 40 тем в бэклоге были повторами.
test('ключ устойчив к регистру, дефисам и падежу', () => {
  assert.equal(dedupeKey('Онлайн-кассы для аптеки'), dedupeKey('онлайн кассы для аптеки'));
  assert.equal(dedupeKey('маркировка обуви'), dedupeKey('Маркировке обуви'));
});

test('stemTokens не режет короткие слова до неразличимости', () => {
  const t = stemTokens('ндс касса чек');
  assert.ok(t.includes('ндс'), 'трёхбуквенные аббревиатуры должны сохраняться');
});

// Склейка от самого Wordstat: «чек коррекции чека коррекции». Формально
// фраза проходит все проверки — длинная, тематическая, — а как тема
// статьи это мусор. Признак склейки: повторяющиеся основы слов.
test('склейка Wordstat отбраковывается по повторам основ', () => {
  assert.ok(isGlued('чек коррекции чека коррекции'), 'две повторённые основы — склейка');
  assert.ok(!isGlued('маркировка обуви в рознице'), 'нормальная фраза не склейка');
  assert.ok(!isGlued('касса для аптеки'), 'короткая фраза не проверяется');
});

test('склейка не проходит фильтр целиком', () => {
  assert.ok(!isInformational('чек коррекции чека коррекции'));
});
